"""Generate the executables in python/ from kb/preamble.sh and a stub.

Each executable is a `sh`/Python polyglot. `sh` runs line 2, the no-op
`''':'`, then the preamble, which chooses an interpreter and re-executes
the file with it. Python reads lines 2 to the closing quotes as a string
literal and runs the stub below it, which finds the repository root and
hands over to kb._bootstrap. The preamble may contain neither three single
quotes nor an invalid Python string escape.

Usage:
  python -m kb.executables            write every executable in COMMANDS
  python -m kb.executables --check    exit 1 if any is missing or stale
  python -m kb.executables --dest DIR --name REL --module MODULE
                                      write one executable (for tests)
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PREAMBLE = ROOT / "kb" / "preamble.sh"
EXECUTABLES = ROOT / "python"

# Executable path under python/ -> the module whose main(argv) it runs.
COMMANDS: dict[str, str] = {
    "adapters/claude/session-end": "kb.commands.adapters.claude.session_end",
}

STUB = """# Generated by kb/executables.py from kb/preamble.sh; do not edit.
import os
import sys


def _root():
    here = os.path.dirname(os.path.realpath(__file__))
    for _ in range(5):
        if os.path.isfile(os.path.join(here, "pyproject.toml")) and os.path.isfile(
            os.path.join(here, "kb", "__init__.py")
        ):
            return here
        here = os.path.dirname(here)
    sys.stderr.write("knowledge base: no repository root within four levels of " + __file__ + "\\n")
    sys.exit(1)


sys.path.insert(0, _root())
from kb import _bootstrap  # noqa: E402

sys.exit(_bootstrap.run({module!r}, __file__))
"""


def render(module: str) -> str:
    preamble = PREAMBLE.read_text(encoding="utf-8")
    if "'''" in preamble:
        raise ValueError("kb/preamble.sh must not contain three single quotes")
    return "#!/bin/sh\n''':'\n" + preamble + "'''\n" + STUB.format(module=module)


def write(dest: Path, name: str, module: str) -> Path:
    path = dest / name
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render(module), encoding="utf-8", newline="")
    path.chmod(0o755)
    return path


def stale() -> list[str]:
    """Executables in COMMANDS that are missing or differ from what render() writes."""
    problems = []
    for name, module in sorted(COMMANDS.items()):
        path = EXECUTABLES / name
        if not path.is_file() or path.read_text(encoding="utf-8", newline="") != render(module):
            problems.append(name)
    return problems


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(prog="python -m kb.executables")
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--dest", type=Path)
    parser.add_argument("--name")
    parser.add_argument("--module")
    args = parser.parse_args(argv)
    if args.dest or args.name or args.module:
        if not (args.dest and args.name and args.module):
            parser.error("--dest, --name, and --module go together")
        write(args.dest, args.name, args.module)
        return 0
    if args.check:
        problems = stale()
        for name in problems:
            print(
                f"python/{name} is missing or stale; run python -m kb.executables", file=sys.stderr
            )
        return 1 if problems else 0
    for name, module in sorted(COMMANDS.items()):
        write(EXECUTABLES, name, module)
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
